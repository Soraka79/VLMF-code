"""Append-only, single-process JSON Lines experiment logging."""

import json
import os
from collections.abc import Mapping
from datetime import datetime, timezone
from pathlib import Path

from flowfm.config import _validate_strict_json


class JsonlLogger:
    """Append strict JSON events; concurrent writers are outside phase-one scope."""

    def __init__(self, path):
        self.path = Path(path).expanduser()

    def log(self, event):
        if not isinstance(event, Mapping):
            raise ValueError("JSONL event must be a mapping containing strict JSON values")
        if "timestamp_utc" in event:
            raise ValueError("timestamp_utc is reserved and generated by JsonlLogger")
        payload = dict(event)
        _validate_strict_json(payload, "JSONL event")
        payload["timestamp_utc"] = (
            datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
        )
        serialized = json.dumps(
            payload,
            ensure_ascii=False,
            allow_nan=False,
            sort_keys=True,
            separators=(",", ":"),
        ) + "\n"

        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.path.open("a", encoding="utf-8") as stream:
            stream.write(serialized)
            stream.flush()
            os.fsync(stream.fileno())
        return self.path


__all__ = ["JsonlLogger"]
